-- podcastdig 初始 schema（MySQL 8.0）
-- 说明：演示环境由 SQLAlchemy Base.metadata.create_all 建表，
-- 本文件是同一结构的可审阅 DDL，供 DBA 在正式环境先行建表。

CREATE TABLE IF NOT EXISTS users (
  id            INT AUTO_INCREMENT PRIMARY KEY,
  email         VARCHAR(160) NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  display_name  VARCHAR(80)  NOT NULL,
  role          VARCHAR(20)  NOT NULL,
  created_at    DATETIME     NOT NULL,
  UNIQUE KEY uq_users_email (email),
  KEY ix_users_role (role)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS feeds (
  id                 INT AUTO_INCREMENT PRIMARY KEY,
  code               VARCHAR(40)  NOT NULL,
  name               VARCHAR(120) NOT NULL,
  show_name          VARCHAR(120) NOT NULL,
  kind               VARCHAR(16)  NOT NULL,
  url                VARCHAR(255) NOT NULL,
  fixture_path       VARCHAR(160) NOT NULL,
  cadence            VARCHAR(32)  NOT NULL,
  host               VARCHAR(60)  NOT NULL,
  active             TINYINT(1)   NOT NULL DEFAULT 1,
  last_fetch_at      DATETIME     NULL,
  last_status        VARCHAR(24)  NOT NULL DEFAULT 'never',
  last_episode_count INT          NOT NULL DEFAULT 0,
  note               TEXT         NULL,
  sort_order         INT          NOT NULL DEFAULT 0,
  created_at         DATETIME     NOT NULL,
  UNIQUE KEY uq_feeds_code (code),
  KEY ix_feeds_kind (kind)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS episodes (
  id               INT AUTO_INCREMENT PRIMARY KEY,
  code             VARCHAR(24)  NOT NULL,
  feed_id          INT          NOT NULL,
  guid             VARCHAR(120) NOT NULL,
  title            VARCHAR(200) NOT NULL,
  duration_seconds INT          NOT NULL,
  published_on     DATE         NOT NULL,
  summary          TEXT         NULL,
  show_notes       TEXT         NULL,
  cover_hint       VARCHAR(24)  NOT NULL DEFAULT 'TAPE',
  season           INT          NOT NULL DEFAULT 1,
  episode_no       INT          NOT NULL DEFAULT 1,
  ingest_state     VARCHAR(16)  NOT NULL DEFAULT 'synced',
  parse_status     VARCHAR(16)  NOT NULL DEFAULT 'pending',
  content_hash     VARCHAR(64)  NOT NULL DEFAULT '',
  chapter_count    INT          NOT NULL DEFAULT 0,
  unparsed_count   INT          NOT NULL DEFAULT 0,
  issue_count      INT          NOT NULL DEFAULT 0,
  parsed_at        DATETIME     NULL,
  updated_at       DATETIME     NOT NULL,
  UNIQUE KEY uq_episodes_code (code),
  UNIQUE KEY uq_episodes_guid (guid),
  KEY ix_episodes_feed (feed_id),
  KEY ix_episodes_published (published_on),
  KEY ix_episodes_parse_status (parse_status),
  KEY ix_episodes_ingest_state (ingest_state),
  CONSTRAINT fk_episodes_feed FOREIGN KEY (feed_id) REFERENCES feeds (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS chapters (
  id            INT AUTO_INCREMENT PRIMARY KEY,
  episode_id    INT          NOT NULL,
  ordinal       INT          NOT NULL DEFAULT 0,
  start_seconds INT          NULL,
  title         VARCHAR(200) NOT NULL DEFAULT '',
  raw_text      TEXT         NULL,
  parse_rule    VARCHAR(32)  NOT NULL DEFAULT '',
  confidence    DOUBLE       NOT NULL DEFAULT 0,
  ambiguous     TINYINT(1)   NOT NULL DEFAULT 0,
  source        VARCHAR(16)  NOT NULL DEFAULT 'parse',
  auto_fixed    TINYINT(1)   NOT NULL DEFAULT 0,
  fix_note      VARCHAR(200) NOT NULL DEFAULT '',
  seed_key      VARCHAR(120) NULL,
  created_at    DATETIME     NOT NULL,
  updated_at    DATETIME     NOT NULL,
  KEY ix_chapters_episode (episode_id),
  KEY ix_chapters_start (start_seconds),
  KEY ix_chapters_source (source),
  UNIQUE KEY uq_chapters_seed_key (seed_key),
  CONSTRAINT fk_chapters_episode FOREIGN KEY (episode_id) REFERENCES episodes (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS chapter_issues (
  id              INT AUTO_INCREMENT PRIMARY KEY,
  issue_key       VARCHAR(160) NOT NULL,
  episode_id      INT          NOT NULL,
  chapter_id      INT          NULL,
  kind            VARCHAR(24)  NOT NULL,
  status          VARCHAR(12)  NOT NULL DEFAULT 'open',
  severity        VARCHAR(12)  NOT NULL DEFAULT 'warn',
  message         TEXT         NULL,
  suggestion      TEXT         NULL,
  window_start    INT          NULL,
  window_end      INT          NULL,
  detected_by     VARCHAR(24)  NOT NULL DEFAULT 'validator',
  resolved_by     VARCHAR(160) NOT NULL DEFAULT '',
  resolved_at     DATETIME     NULL,
  resolution_note VARCHAR(255) NOT NULL DEFAULT '',
  seed_key        VARCHAR(120) NULL,
  created_at      DATETIME     NOT NULL,
  UNIQUE KEY uq_issues_key (issue_key),
  UNIQUE KEY uq_issues_seed_key (seed_key),
  KEY ix_issues_episode (episode_id),
  KEY ix_issues_kind (kind),
  KEY ix_issues_status (status),
  KEY ix_issues_chapter (chapter_id),
  CONSTRAINT fk_issues_episode FOREIGN KEY (episode_id) REFERENCES episodes (id),
  CONSTRAINT fk_issues_chapter FOREIGN KEY (chapter_id) REFERENCES chapters (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS digest_tasks (
  id                 INT AUTO_INCREMENT PRIMARY KEY,
  code               VARCHAR(24) NOT NULL,
  mode               VARCHAR(12) NOT NULL,
  status             VARCHAR(12) NOT NULL DEFAULT 'queued',
  feed_scope         VARCHAR(160) NOT NULL DEFAULT 'all',
  triggered_by       VARCHAR(160) NOT NULL DEFAULT '',
  triggered_role     VARCHAR(20)  NOT NULL DEFAULT '',
  feeds_scanned      INT NOT NULL DEFAULT 0,
  episodes_scanned   INT NOT NULL DEFAULT 0,
  episodes_new       INT NOT NULL DEFAULT 0,
  episodes_updated   INT NOT NULL DEFAULT 0,
  episodes_unchanged INT NOT NULL DEFAULT 0,
  chapters_parsed    INT NOT NULL DEFAULT 0,
  unparsed_chapters  INT NOT NULL DEFAULT 0,
  issues_found       INT NOT NULL DEFAULT 0,
  duration_ms        INT NOT NULL DEFAULT 0,
  log_lines          JSON NULL,
  error_text         TEXT NULL,
  started_at         DATETIME NULL,
  finished_at        DATETIME NULL,
  seed_key           VARCHAR(120) NULL,
  created_at         DATETIME NOT NULL,
  UNIQUE KEY uq_tasks_code (code),
  UNIQUE KEY uq_tasks_seed_key (seed_key),
  KEY ix_tasks_status (status),
  KEY ix_tasks_mode (mode),
  KEY ix_tasks_created (created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS audit_logs (
  id          INT AUTO_INCREMENT PRIMARY KEY,
  actor_email VARCHAR(160) NOT NULL,
  actor_role  VARCHAR(20)  NOT NULL,
  action      VARCHAR(64)  NOT NULL,
  entity      VARCHAR(40)  NOT NULL,
  entity_id   VARCHAR(64)  NULL,
  detail      JSON NULL,
  layer       VARCHAR(16)  NOT NULL DEFAULT 'domain',
  ip          VARCHAR(64)  NULL,
  seed_key    VARCHAR(120) NULL,
  created_at  DATETIME     NOT NULL,
  UNIQUE KEY uq_audit_seed_key (seed_key),
  KEY ix_audit_actor (actor_email),
  KEY ix_audit_action (action),
  KEY ix_audit_created (created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
